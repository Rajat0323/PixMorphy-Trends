export function t(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>) {
  let text: string = translations[locale][key] ?? translations.hi[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

export function getNavLabel(locale: Locale, id: string) {
  const map: Record<string, TranslationKey> = {
    home: "navHome",
    blog: "navBlog",
    query: "navQuery",
    contact: "navContact",
  };
  const key = map[id];
  return key ? t(locale, key) : id;
}
